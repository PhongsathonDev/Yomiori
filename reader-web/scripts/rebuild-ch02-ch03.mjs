function getChar(id) {
  const c = characters.find(x => x.id === id);
  if (!c) {
    if (id === 'clerk') return { id: 'clerk', name: 'พนักงานร้านสะดวกซื้อ' };
    return { id, name: id };
  }
  return { id: c.id, name: c.name };
}

