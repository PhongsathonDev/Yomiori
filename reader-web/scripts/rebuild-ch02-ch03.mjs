function buildChapter(chNum, rawFilename, speakerRules) {
  const rawPath = path.resolve('../novels_source/kyudo-senpai/raw_chapters', rawFilename);
  const rawContent = fs.readFileSync(rawPath, 'utf8');

  let title = `ตอนที่ ${chNum}`;
  const titleMatch = rawContent.match(/^#\s*(Ch[._]\d+.*?)$/m);
  if (titleMatch) title = titleMatch[1].trim();

  const lines = rawContent.split(/\r?\n/);
  const rawParas = [];
  let curr = [];

  for (let l of lines) {
    l = l.trim();
    if (!l) {
      if (curr.length > 0) {
        rawParas.push(curr.join(' '));
        curr = [];
      }
      continue;
    }
    if (l.startsWith('#') || l.startsWith('By ') || l.startsWith('AI-POWERED')) continue;
    curr.push(l);
  }
  if (curr.length > 0) rawParas.push(curr.join(' '));

  const sortedRules = [...speakerRules].sort((a, b) => b.match.length - a.match.length);

  const blocks = [];
  let bIdx = 1;

  for (const para of rawParas) {
    if (para === '◆' || para === '◆ ◆ ◆' || para === '❖ ❖ ❖') {
      blocks.push({
        id: `b${chNum}-${bIdx++}`,
        type: 'scene_break',
        symbol: para
      });
      continue;
    }

    if (para.startsWith('“') && para.endsWith('”')) {
      const cleanPara = para.replace(/[“”]/g, '').trim();
      let matchedRule = null;

      for (const r of sortedRules) {
        if (r.exact) {
          if (cleanPara === r.match) {
            matchedRule = r;
            break;
          }
        } else {
          if (cleanPara.includes(r.match)) {
            matchedRule = r;
            break;
          }
        }
      }

      const spId = matchedRule ? matchedRule.id : 'toya';
      const c = getChar(spId);

      blocks.push({
        id: `b${chNum}-${bIdx++}`,
        type: 'dialogue',
        speakerId: c.id,
        speakerName: c.name,
        text: para
      });
    } else {
      blocks.push({
        id: `b${chNum}-${bIdx++}`,
        type: 'narration',
        text: para
      });
    }
  }

  const pad = String(chNum).padStart(2, '0');
  const chapterData = {
    id: `ch-${pad}`,
    novelId: 'kyudo-senpai',
    chapterNumber: chNum,
    title,
    novelTitle: '(WN) รุ่นพี่สาวสวยจากชมรมยิงธนู ผมนอนในห้องของผมโดยที่ท้องของเธอเปิดโล่ง',
    blocks
  };

  const destPath = path.resolve('src/data/novels/kyudo-senpai/chapters', `ch-${pad}.json`);
  fs.writeFileSync(destPath, JSON.stringify(chapterData, null, 2), 'utf8');
  console.log(`✅ Perfectly rebuilt Ch.${chNum}: ${blocks.length} blocks saved to ${destPath}`);
}

