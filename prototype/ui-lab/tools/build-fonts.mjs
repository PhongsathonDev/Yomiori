/**
 * Download the handwriting accent used by mockup C. Run once.
 *
 *   node prototype/ui-lab/tools/build-fonts.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const labDir = path.resolve(here, '..');
const fontsDir = path.join(labDir, 'assets', 'fonts');
const outFile = path.join(labDir, 'shared', 'mali.css');
const chromeUa =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';

fs.mkdirSync(fontsDir, { recursive: true });

const css = await (
  await fetch('https://fonts.googleapis.com/css2?family=Mali:wght@400;600&display=swap', {
    headers: { 'User-Agent': chromeUa },
  })
).text();

const rules = [];
for (const block of css.matchAll(/@font-face\s*\{[^}]*\}/g)) {
  const rule = block[0];
  const range = rule.match(/unicode-range:\s*([^;]+);/)?.[1] || '';
  if (!/U\+0E01/.test(range) && !/U\+0000-00FF/.test(range)) continue;
  const src = rule.match(/url\((https:\/\/[^)]+\.woff2)\)/);
  if (!src) continue;
  const slug = `mali-${path.basename(new URL(src[1]).pathname)}`;
  const response = await fetch(src[1], { headers: { 'User-Agent': chromeUa } });
  if (!response.ok) throw new Error(`Font download failed: ${response.status}`);
  fs.writeFileSync(path.join(fontsDir, slug), Buffer.from(await response.arrayBuffer()));
  rules.push(rule.replace(src[1], `../assets/fonts/${slug}`));
}

fs.writeFileSync(
  outFile,
  `/* Generated by tools/build-fonts.mjs. Source: Google Fonts (OFL). */\n${rules.join('\n\n')}\n`,
  'utf8',
);
console.log(`Wrote shared/mali.css · ${rules.length} faces`);
