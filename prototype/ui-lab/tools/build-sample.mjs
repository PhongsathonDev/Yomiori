/**
 * Build a small, realistic sample for the three UI directions.
 * It reads the read-only v2 data snapshot; it does not touch reader-web.
 *
 *   node prototype/ui-lab/tools/build-sample.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const labDir = path.resolve(here, '..');
const v2DataFile = path.resolve(labDir, '..', 'web-v2', 'js', 'data.js');
const outFile = path.join(labDir, 'shared', 'sample.js');

const source = fs.readFileSync(v2DataFile, 'utf8');
const sandbox = { window: {} };
vm.runInNewContext(source, sandbox, { filename: 'web-v2/js/data.js' });
const data = sandbox.window.YOMIORI_V2_DATA;

const picks = ['kyudo-senpai', 'black-cat-hangout', 'boyish-friend', 'makeine-too-many-losing-heroines'];

function asset(url) {
  if (!url) return null;
  if (/^(https?:|\/)/.test(url)) return url;
  return `/web-v2/${url}`;
}

const novels = picks.map((id) => {
  const novel = data.novels.find((item) => item.id === id);
  if (!novel) throw new Error(`Missing novel: ${id}`);

  const chapters = novel.chapters
    .filter((chapter) => chapter.chapterNumber >= 0 && chapter.chapterNumber <= 8)
    .map((chapter) => ({
      id: chapter.id,
      number: chapter.chapterNumber,
      title: chapter.title.replace(/^Ch\.\s*\d+\s*[—–-]\s*/i, ''),
      blocks:
        chapter.chapterNumber >= 1 && chapter.chapterNumber <= 3
          ? chapter.blocks.slice(0, 22).map((block) => {
              if (block.type === 'illustration') {
                return { ...block, src: asset(block.src) };
              }
              return block;
            })
          : [],
    }));

  return {
    id: novel.id,
    title: novel.title,
    originalTitle: novel.originalTitle,
    author: novel.author,
    artist: novel.artist,
    synopsis: novel.synopsis,
    tags: novel.tags,
    totalOriginalChapters: novel.totalOriginalChapters,
    cover: asset(novel.cover),
    banner: asset(novel.banner),
    chapters,
    characters: novel.characters.slice(0, 6).map((character) => ({
      id: character.id,
      name: character.name,
      role: character.role,
      color: character.color,
      avatar: asset(character.avatar),
    })),
    illustrations: novel.illustrations.slice(0, 4).map((illustration) => ({
      id: illustration.id,
      title: illustration.title,
      src: asset(illustration.src),
    })),
  };
});

const payload = {
  generatedFrom: data.generatedFrom,
  generatedAt: new Date().toISOString(),
  novels,
};

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(
  outFile,
  `/* Generated by tools/build-sample.mjs from web-v2/js/data.js. */\nwindow.LAB_DATA = ${JSON.stringify(payload)};\n`,
  'utf8',
);

const blocks = novels.reduce(
  (sum, novel) => sum + novel.chapters.reduce((inner, chapter) => inner + chapter.blocks.length, 0),
  0,
);
console.log(
  `Wrote shared/sample.js · ${novels.length} novels · ${novels.reduce(
    (sum, novel) => sum + novel.chapters.length,
    0,
  )} chapter rows · ${blocks} blocks · ${(fs.statSync(outFile).size / 1024).toFixed(0)} KB`,
);
