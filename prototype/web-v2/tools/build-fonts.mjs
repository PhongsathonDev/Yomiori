/**
 * Download the prototype's webfonts once and store them beside the mockup so
 * the preview also works offline from a local static server.
 *
 * Only Thai, Latin and punctuation subsets are kept. Shippori Mincho is
 * subset to the two wordmark characters (読織) so it stays a few kilobytes.
 *
 * Run from the repository root:
 *   node prototype/web-v2/tools/build-fonts.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const prototypeDir = path.resolve(here, '..');
const fontsDir = path.join(prototypeDir, 'assets', 'fonts');
const cssDir = path.join(prototypeDir, 'css');

const families = [
  { family: 'IBM Plex Sans Thai Looped', axis: 'wght@400;500;600' },
  { family: 'IBM Plex Sans Thai', axis: 'wght@400;500;600' },
  { family: 'Noto Serif Thai', axis: 'wght@400;500;600;700' },
];

const chromeUa =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';

fs.rmSync(fontsDir, { recursive: true, force: true });
fs.mkdirSync(fontsDir, { recursive: true });
fs.mkdirSync(cssDir, { recursive: true });

const blocks = [];
let downloaded = 0;

function keepSubset(rule) {
  const range = rule.match(/unicode-range:\s*([^;]+);/)?.[1] || '';
  return /U\+0E01/.test(range) || /U\+0000-00FF/.test(range) || /U\+0100-02/.test(range) || /U\+2000-206F/.test(range);
}

async function fetchCss(url) {
  const response = await fetch(url, { headers: { 'User-Agent': chromeUa } });
  if (!response.ok) throw new Error(`Font CSS failed (${response.status}): ${url}`);
  return response.text();
}

async function saveFace(rule) {
  const src = rule.match(/url\((https:\/\/[^)]+\.woff2)\)/);
  if (!src) return;
  const familySlug = (rule.match(/font-family:\s*'([^']+)'/)?.[1] || 'font').toLowerCase().replace(/[^a-z0-9]+/g, '-');
  const slug = `${familySlug}-${path.basename(new URL(src[1]).pathname)}`;
  const target = path.join(fontsDir, slug);
  if (!fs.existsSync(target)) {
    const font = await fetch(src[1], { headers: { 'User-Agent': chromeUa } });
    if (!font.ok) throw new Error(`Font file failed (${font.status}): ${src[1]}`);
    fs.writeFileSync(target, Buffer.from(await font.arrayBuffer()));
    downloaded += 1;
  }
  blocks.push(rule.replace(src[1], `../assets/fonts/${slug}`));
}

for (const { family, axis } of families) {
  const css = await fetchCss(
    `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family).replace(/%20/g, '+')}:${axis}&display=swap`,
  );
  let kept = 0;
  for (const block of css.matchAll(/@font-face\s*\{[^}]*\}/g)) {
    if (!keepSubset(block[0])) continue;
    await saveFace(block[0]);
    kept += 1;
  }
  console.log(`Fetched ${family} ${axis} · ${kept} subsets`);
}

const wordmarkCss = await fetchCss(
  `https://fonts.googleapis.com/css2?family=Shippori+Mincho:wght@500;600&text=${encodeURIComponent('読織')}&display=swap`,
);
for (const block of wordmarkCss.matchAll(/@font-face\s*\{[^}]*\}/g)) {
  await saveFace(block[0]);
}
console.log('Fetched Shippori Mincho · wordmark subset');

fs.writeFileSync(
  path.join(cssDir, 'fonts.css'),
  `/* Generated by tools/build-fonts.mjs. Source: Google Fonts (OFL). */\n${blocks.join('\n\n')}\n`,
  'utf8',
);
console.log(`Wrote css/fonts.css · ${blocks.length} faces · ${downloaded} new files`);
